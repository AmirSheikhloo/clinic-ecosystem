const PERSIAN_LETTER = /[\u0600-\u06FF]/;

/** Prefer a mapped Persian message; keep server text only when it is already Persian. */
export function describeError(code: string | undefined, message: string | undefined, fallback: string): string {
  if (code && ERROR_FA[code]) return ERROR_FA[code];
  if (message && PERSIAN_LETTER.test(message)) return message;
  return fallback;
}
